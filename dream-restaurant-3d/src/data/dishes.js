/** 以 id 取得菜色，找不到時回傳 undefined。 */
export function dishById(id) {
  return DISHES.find((dish) => dish.id === id);
}

/** 取得在指定星級已解鎖的菜色（entry.stars <= stars）。 */
export function dishesForStars(stars) {
  return DISHES.filter((dish) => dish.stars <= stars);
}

